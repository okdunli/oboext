/**
 * Cookie remembering an explicit language choice. The URL prefix stays the
 * only RENDER signal (SSR and hydration must agree without a round-trip);
 * this cookie only decides where a prefix-free URL should LAND: a visitor
 * who picked English is sent to /en once per session instead of silently
 * falling back to the default locale. A stale or foreign value is ignored,
 * so the cookie can never poison the resolution below the URL prefix.
 */
export const LOCALE_COOKIE = "oboext_locale";

/** One year, in seconds — long enough to outlive a browser restart. */
const LOCALE_COOKIE_MAX_AGE = 365 * 24 * 60 * 60;

/** Set-Cookie VALUE recording the locale. Written by the switcher (client)
 * and by the middleware redirect (server), so both paths stay in sync. */
export function localeCookieValue(locale: Locale): string {
  return [
    `${LOCALE_COOKIE}=${locale}`,
    "SameSite=Lax",
    "Path=/",
    `Max-Age=${LOCALE_COOKIE_MAX_AGE}`,
    ...(process.env.NODE_ENV === "production" ? ["Secure"] : []),
  ].join("; ");
}

/**
 * The remembered locale from a raw Cookie header, or null. Tolerates the
 * whole header (other cookies ride along), surrounding whitespace, and
 * percent-encoding; an unknown value yields null so callers fall through
 * to the next signal.
 */
export function localeFromCookieHeader(header: unknown): Locale | null {
  if (typeof header !== "string" || !header) return null;
  for (const part of header.split(";")) {
    const eq = part.indexOf("=");
    if (eq < 0) continue;
    if (part.slice(0, eq).trim() !== LOCALE_COOKIE) continue;
    let raw = part.slice(eq + 1).trim();
    try {
      raw = decodeURIComponent(raw);
    } catch (e) {
      /* keep the raw bytes; normalizeLocale rejects anything unknown */
    }
    return normalizeLocale(raw);
  }
  return null;
}

/**
 * Resolve the locale for a request: the URL prefix wins (it is what the
 * visitor sees and shares), then an explicit cookie choice, then the
 * browser's Accept-Language, then the default. The prefixed locales are
 * the only ones worth remembering — the default is already prefix-free,
 * so remembering it changes nothing.
 */
export function resolveLocale(input: {
  url?: unknown;
  cookie?: unknown;
  accept?: unknown;
}): Locale {
  const fromUrl = splitLocalePath(input.url);
  if (fromUrl.prefixed) return fromUrl.locale;
  const fromCookie = localeFromCookieHeader(input.cookie);
  if (fromCookie && fromCookie !== DEFAULT_LOCALE) return fromCookie;
  for (const cand of parseAcceptLanguage(input.accept)) return cand;
  return DEFAULT_LOCALE;
}

/**
 * The request locale off a context-like object, defaulting when the
 * middleware did not set one. API routes read it to pick the language of
 * their JSON error messages (the middleware fills ctx.locale from the
 * client-stamped x-locale header for /api/* paths).
 */
export function ctxLocale(ctx?: { locale?: string } | null): Locale {
  const raw = ctx && ctx.locale;
  return raw === "en" || raw === "zh-CN" ? raw : DEFAULT_LOCALE;
}

/**
 * Request locale off the client-stamped `x-locale` header. The bilingual
 * public scripts (login card, register, comments) stamp the header on every
 * API call; a plain curl without it falls back to Chinese, which is what the
 * admin surfaces read anyway.
 */
export function headerLocale(req: {
  headers: { get(name: string): string | null };
}): Locale {
  return ctxLocale({ locale: req.headers.get("x-locale") ?? undefined });
}

/**
 * Request locale for CACHEABLE GET /api/* bodies. The hot cache keys on
 * pathname+query+cookie (BUG.md AB), so a locale negotiated on the x-locale
 * header is replayed across languages: the first request's error message wins
 * for the whole TTL, in either direction. The bilingual clients therefore
 * stamp the locale into the query as well (?l=), which IS part of the key; a
 * request without it gets the default locale deterministically instead of
 * whatever the first caller happened to send. POST bodies are never cached and
 * keep reading the header (headerLocale).
 */
export function apiLocale(req: {
  url: string;
  headers: { get(name: string): string | null };
}): Locale {
  let tag = "";
  try {
    tag = new URL(req.url).searchParams.get("l") || "";
  } catch {
    tag = "";
  }
  return ctxLocale({ locale: tag.trim() });
}

/**
 * Locale from an Accept-Language header. The first-run installer has no URL
 * prefix and no locale cookie to read, so the browser's preference is the
 * only signal that can exist at that point.
 */
export function acceptLanguageLocale(al: string): Locale {
  for (const part of String(al || "").split(",")) {
    const tag = part.split(";")[0].trim().toLowerCase();
    if (!tag) continue;
    if (tag.startsWith("zh")) return "zh-CN";
    if (tag.startsWith("en")) return "en";
  }
  return DEFAULT_LOCALE;
}

// ------------------------------------------------------------------ rendering

export type Translate = (key: string, vars?: Record<string, string | number>) => string;

/** A bound translator for one locale. Unknown keys render as the key. */
export function makeT(locale: Locale): Translate {
  const cat = catalogFor(locale);
  return (key, vars) => {
    let s = cat[key];
    if (s == null) s = key;
    if (vars) {
      for (const k of Object.keys(vars)) {
        s = s.split(`{${k}}`).join(String(vars[k]));
      }
    }
    return s;
  };
}

/** One-shot translate (tests and one-off call sites). */
export function translate(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  return makeT(locale)(key, vars);
}

// ------------------------------------------------------------------- URLs

/** First path segments that must never take a locale prefix. */
const NO_PREFIX_SEGMENTS = new Set([
  "api",
  "public",
  "uploads",
  "theme-assets",
  "plugin-assets",
  "theme-style",
  "admin",
  "en",
  "feed",
  "feed.xml",
  "rss.xml",
  "sitemap.xml",
  "robots.txt",
  "manifest.webmanifest",
  "favicon.ico",
]);

/**
 * Prefix every root-relative href/action in a rendered HTML fragment so
 * navigation stays inside the locale. Assets, APIs, feeds and the admin keep
 * their canonical paths; protocol-relative and non-root URLs are untouched.
 * The default locale is a no-op, which is what keeps the zh-CN output
 * byte-identical to before this feature existed.
 */
export function prefixLocaleUrls(html: string, locale: Locale): string {
  if (!html || locale === DEFAULT_LOCALE) return html;
  // R280: anchors carrying data-locale-keep name documents in ANOTHER locale
  // (a translation pair's counterpart). Their href already describes the
  // destination's own tree; re-prefixing to the current locale would turn
  // "read the English version" into the same-language page. Split first so
  // the skip can look at the anchor's own attribute run.
  const parts = html.split(/(?=<a\s)/);
  return parts
    .map((chunk) =>
      chunk.startsWith("<a") && chunk.includes("data-locale-keep")
        ? chunk
        : chunk.replace(/(href|action)="(\/[^"]*)"/g, (full, attr: string, urlPath: string) => {
            if (urlPath.startsWith("//")) return full;
            const seg = urlPath.slice(1).split(/[/?#]/)[0];
            if (NO_PREFIX_SEGMENTS.has(seg)) return full;
            if (urlPath === "/") return `${attr}="/en/"`;
            return `${attr}="/en${urlPath}"`;
          }),
    )
    .join("");
}

/**
 * Whether real per-locale content EXISTS (any post carries a translation
 * pairing). i18n stays dependency-free: the data layer (loaders) probes the
 * DB and calls setPairingActive(); canonicalPath/hreflangLinks read the flag.
 * Default false = R269 semantics (merge + no cluster).
 */
let pairingActive = false;
export function setPairingActive(on: boolean): void {
  pairingActive = on;
}
export function isPairingActive(): boolean {
  return pairingActive || process.env.OBOEXT_HREFLANG_CLUSTER === "1";
}

/**
 * The canonical path for a page in a given locale.
 *
 * NO pairing (default, R269): /en/x and /x are one document — the canonical
 * MERGES into the default URL; the prefixed form stays navigational only.
 * PAIRING ACTIVE (R274: at least one translation pair exists): each locale's
 * URL is its own document again, so the canonical goes back to
 * self-referencing and hreflangLinks declares the true pair.
 *
 * The call contract is unchanged for every caller: build the canonical with
 * the request's locale exactly as before. The trailing-slash rule: "/" stays
 * "/" for the default locale and becomes "/en" when self-referencing (the
 * slash form answers a 308).
 */
export function canonicalPath(path: string, locale: Locale): string {
  if (locale === DEFAULT_LOCALE) return path;
  if (!isPairingActive()) return path; // R269 merge
  const p = path === "/" ? "" : path;
  return `/${locale}${p}`;
}

/**
 * hreflang alternates for the document head.
 *
 * NO pairing: EMPTY. The en URL's canonical merges into the default, so
 * declaring it as an alternate would contradict our own canonical (R269).
 *
 * PAIRING ACTIVE: both locales plus x-default, self-canonicalising per
 * locale — the original rule ("every listed alternate must confirm the page
 * back") is satisfiable again because each URL now has its own body. The
 * head block dedupes by name|rel, so a distinct name per link keeps all
 * three from collapsing into one.
 */
export function hreflangLinks(origin: string, path: string): string {
  if (!isPairingActive()) return "";
  const base = `${origin || ""}${path}`;
  const en = `${origin || ""}${canonicalPath(path, "en")}`;
  return (
    `<link name="hreflang-zh-CN" rel="alternate" hreflang="zh-CN" href="${base}">` +
    `<link name="hreflang-en" rel="alternate" hreflang="en" href="${en}">` +
    `<link name="hreflang-x-default" rel="alternate" hreflang="x-default" href="${base}">`
  );
}
