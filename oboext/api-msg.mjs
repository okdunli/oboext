export function apiMsg(zh, ctx) {
  if (!enRequest(ctx)) return zh;
  // Size-limit messages are built at runtime with the live MB cap, so the
  // catalog keys cannot match them statically - three shapes, matched here.
  const size = zh.match(/^([^（]{1,6})过大（上限 (\d+)MB）$/);
  if (size) return `${size[1]} is too large (limit ${size[2]}MB)`;
  const cap = zh.match(/^(插件包|安装包)不能超过 (\d+)MB$/);
  if (cap) return `The ${cap[1] === "插件包" ? "plugin package" : "package"} must be at most ${cap[2]}MB`;
  return EN[zh] ?? zh;
}

function enRequest(ctx) {
  const req = ctx && ctx.request;
  if (!req || !req.headers) return false;
  const cookie = req.headers.get("cookie") || "";
  if (/(?:^|;\s*)oboext_locale=en(?:\s*;|$)/.test(cookie)) return true;
  // an explicit cookie for another locale wins over Accept-Language
  if (/(?:^|;\s*)oboext_locale=/.test(cookie)) return false;
  return /^en\b/.test(req.headers.get("accept-language") || "");
}
